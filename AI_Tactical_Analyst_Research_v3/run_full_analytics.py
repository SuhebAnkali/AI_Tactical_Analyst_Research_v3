"""Run the complete post-processing and analytics workflow for a full video.

This orchestrator uses the outputs already generated by ``run_pipeline.py``:

    outputs/final_full_video/tracks.csv
    outputs/final_full_video/ball.csv
    outputs/final_full_video/annotated.mp4

It then runs, in order:

1. Data preprocessing
2. Feature engineering
3. Tactical frame analytics
4. Possession analytics V2
5. Transition analysis
6. Passing-network analysis
7. Player-influence analysis
8. Detailed PDF and JSON report generation

The script stops immediately if any stage fails, so an incomplete result is not
mistaken for a successful final analysis.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path


class FullAnalyticsRunner:
    """Execute every final analytics stage with consistent paths."""

    def __init__(
        self,
        run_directory: str | Path,
        analytics_directory: str | Path | None = None,
        reports_directory: str | Path | None = None,
    ) -> None:
        self.run_directory = Path(run_directory)

        self.analytics_directory = (
            Path(analytics_directory)
            if analytics_directory is not None
            else self.run_directory / "analytics"
        )

        self.reports_directory = (
            Path(reports_directory)
            if reports_directory is not None
            else self.run_directory / "reports"
        )

        self.tracks_csv = self.run_directory / "tracks.csv"
        self.ball_csv = self.run_directory / "ball.csv"

        self.analytics_directory.mkdir(parents=True, exist_ok=True)
        self.reports_directory.mkdir(parents=True, exist_ok=True)

    def validate_inputs(self) -> None:
        missing: list[Path] = []

        for path in (self.tracks_csv, self.ball_csv):
            if not path.exists():
                missing.append(path)

        if missing:
            joined = "\n".join(f"- {path}" for path in missing)
            raise FileNotFoundError(
                "Required full-video pipeline outputs are missing:\n"
                f"{joined}"
            )

    def run(self) -> None:
        self.validate_inputs()

        cleaned_tracks = self.analytics_directory / "cleaned_tracks.csv"
        preprocessing_report = (
            self.analytics_directory / "preprocessing_report.json"
        )

        player_statistics = (
            self.analytics_directory / "player_statistics.csv"
        )
        team_statistics = (
            self.analytics_directory / "team_statistics.csv"
        )
        feature_report = (
            self.analytics_directory / "feature_engineering_report.json"
        )

        tactical_timeline = (
            self.analytics_directory / "tactical_timeline.csv"
        )
        tactical_summary = (
            self.analytics_directory / "tactical_summary.csv"
        )
        tactical_report = (
            self.analytics_directory / "tactical_analytics_report.json"
        )

        possession_timeline = (
            self.analytics_directory / "possession_timeline_v2.csv"
        )
        possession_summary = (
            self.analytics_directory / "possession_summary_v2.csv"
        )
        possession_report = (
            self.analytics_directory / "possession_report_v2.json"
        )

        transition_timeline = (
            self.analytics_directory / "transition_timeline.csv"
        )
        transition_summary = (
            self.analytics_directory / "transition_summary.csv"
        )
        transition_report = (
            self.analytics_directory / "transition_report.json"
        )

        pass_events = self.analytics_directory / "pass_events.csv"
        passing_edges = (
            self.analytics_directory / "passing_network_edges.csv"
        )
        passing_nodes = (
            self.analytics_directory / "passing_network_nodes.csv"
        )
        passing_report = (
            self.analytics_directory / "passing_network_report.json"
        )

        player_influence = (
            self.analytics_directory / "player_influence.csv"
        )
        player_rankings = (
            self.analytics_directory / "player_rankings.csv"
        )
        influence_report = (
            self.analytics_directory / "player_influence_report.json"
        )

        detailed_pdf = (
            self.reports_directory / "match_report_detailed.pdf"
        )
        detailed_json = (
            self.reports_directory / "match_summary_detailed.json"
        )

        stages: list[tuple[str, list[str]]] = [
            (
                "Data preprocessing",
                [
                    "-m",
                    "src.analytics.preprocessing",
                    "--input",
                    str(self.tracks_csv),
                    "--output",
                    str(cleaned_tracks),
                    "--report",
                    str(preprocessing_report),
                ],
            ),
            (
                "Feature engineering",
                [
                    "-m",
                    "src.analytics.feature_engineering",
                    "--input",
                    str(cleaned_tracks),
                    "--player-output",
                    str(player_statistics),
                    "--team-output",
                    str(team_statistics),
                    "--report",
                    str(feature_report),
                ],
            ),
            (
                "Tactical frame analytics",
                [
                    "-m",
                    "src.analytics.tactical_timeline",
                    "--input",
                    str(cleaned_tracks),
                    "--timeline-output",
                    str(tactical_timeline),
                    "--summary-output",
                    str(tactical_summary),
                    "--report",
                    str(tactical_report),
                ],
            ),
            (
                "Possession analytics V2",
                [
                    "-m",
                    "src.analytics.possession_analytics_v2",
                    "--players",
                    str(cleaned_tracks),
                    "--ball",
                    str(self.ball_csv),
                    "--timeline-output",
                    str(possession_timeline),
                    "--summary-output",
                    str(possession_summary),
                    "--report",
                    str(possession_report),
                ],
            ),
            (
                "Transition analysis",
                [
                    "-m",
                    "src.analytics.transition_analysis",
                    "--tracks",
                    str(cleaned_tracks),
                    "--tactical",
                    str(tactical_timeline),
                    "--possession",
                    str(possession_timeline),
                    "--timeline-output",
                    str(transition_timeline),
                    "--summary-output",
                    str(transition_summary),
                    "--report",
                    str(transition_report),
                ],
            ),
            (
                "Passing-network analysis",
                [
                    "-m",
                    "src.analytics.passing_network",
                    "--tracks",
                    str(cleaned_tracks),
                    "--possession",
                    str(possession_timeline),
                    "--pass-events-output",
                    str(pass_events),
                    "--edges-output",
                    str(passing_edges),
                    "--nodes-output",
                    str(passing_nodes),
                    "--report",
                    str(passing_report),
                ],
            ),
            (
                "Player-influence analysis",
                [
                    "-m",
                    "src.analytics.player_influence",
                    "--tracks",
                    str(cleaned_tracks),
                    "--player-stats",
                    str(player_statistics),
                    "--possession",
                    str(possession_timeline),
                    "--transition",
                    str(transition_timeline),
                    "--network-nodes",
                    str(passing_nodes),
                    "--influence-output",
                    str(player_influence),
                    "--rankings-output",
                    str(player_rankings),
                    "--report",
                    str(influence_report),
                ],
            ),
            (
                "Detailed research report",
                [
                    "-m",
                    "src.reports.match_report_generator",
                    "--cleaned-tracks",
                    str(cleaned_tracks),
                    "--ball",
                    str(self.ball_csv),
                    "--player-statistics",
                    str(player_statistics),
                    "--team-statistics",
                    str(team_statistics),
                    "--tactical-timeline",
                    str(tactical_timeline),
                    "--tactical-summary",
                    str(tactical_summary),
                    "--possession-timeline",
                    str(possession_timeline),
                    "--possession-summary",
                    str(possession_summary),
                    "--transition-timeline",
                    str(transition_timeline),
                    "--transition-summary",
                    str(transition_summary),
                    "--passing-edges",
                    str(passing_edges),
                    "--passing-nodes",
                    str(passing_nodes),
                    "--player-influence",
                    str(player_influence),
                    "--player-rankings",
                    str(player_rankings),
                    "--preprocessing-report",
                    str(preprocessing_report),
                    "--feature-report",
                    str(feature_report),
                    "--tactical-report",
                    str(tactical_report),
                    "--possession-report",
                    str(possession_report),
                    "--transition-report",
                    str(transition_report),
                    "--passing-report",
                    str(passing_report),
                    "--influence-report",
                    str(influence_report),
                    "--pdf-output",
                    str(detailed_pdf),
                    "--json-output",
                    str(detailed_json),
                ],
            ),
        ]

        total = len(stages)

        for index, (name, arguments) in enumerate(stages, start=1):
            print()
            print("=" * 72)
            print(f"[{index}/{total}] {name}")
            print("=" * 72)

            command = [sys.executable, *arguments]
            result = subprocess.run(command, check=False)

            if result.returncode != 0:
                raise RuntimeError(
                    f"Stage failed: {name}\n"
                    f"Exit code: {result.returncode}"
                )

        print()
        print("=" * 72)
        print("FULL ANALYTICS WORKFLOW COMPLETED")
        print("=" * 72)
        print("Analytics folder:", self.analytics_directory.resolve())
        print("Reports folder:", self.reports_directory.resolve())
        print("Detailed PDF:", detailed_pdf.resolve())
        print("Detailed JSON:", detailed_json.resolve())


def parse_arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Run every analytics module and generate the final report "
            "for a completed full-video pipeline run."
        )
    )

    parser.add_argument(
        "--run-dir",
        default="outputs/final_full_video",
        help=(
            "Directory containing tracks.csv and ball.csv from "
            "run_pipeline.py."
        ),
    )

    parser.add_argument(
        "--analytics-dir",
        default=None,
        help=(
            "Optional analytics output directory. Default: "
            "<run-dir>/analytics"
        ),
    )

    parser.add_argument(
        "--reports-dir",
        default=None,
        help=(
            "Optional report output directory. Default: "
            "<run-dir>/reports"
        ),
    )

    return parser.parse_args()


def main() -> None:
    args = parse_arguments()

    runner = FullAnalyticsRunner(
        run_directory=args.run_dir,
        analytics_directory=args.analytics_dir,
        reports_directory=args.reports_dir,
    )

    try:
        runner.run()
    except (FileNotFoundError, RuntimeError) as error:
        print()
        print("ERROR:", error)
        raise SystemExit(1) from error


if __name__ == "__main__":
    main()
